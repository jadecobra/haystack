export function sicForTicker(ticker: string): number | null {
  const code = SP500_SIC[ticker.toUpperCase()];
  return typeof code === "number" ? code : null;
}

/** SEC industry name for a SIC that appears on the S&P screen, or null. */
export function sicIndustryName(sic: number): string | null {
  const name = SP500_SIC_NAMES[String(sic)];
  return name ? name : null;
}

/** Parse `?sic=` as a 1–4 digit code. Anything else is not a filter. */
export function parseSicQuery(value: string | null): number | null {
  if (!value || !/^\d{1,4}$/.test(value)) return null;
  return Number(value);
}
